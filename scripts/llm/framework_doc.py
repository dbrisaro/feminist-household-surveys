"""Write framework/FRAMEWORK.md, the readable version of the evaluation framework.

Reads framework.json through framework.load(), so the document shows exactly what parse_framework.py
lifted from gender_survey_framework.html and what the classification sends to the model: the four
subdimensions with their variables and, for each indicator, its identifier, type, source types and
text, with the elements of each criterion list and the options of the categorical indicator. Nothing
is typed by hand.

    python scripts/llm/framework_doc.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import framework as framework_mod  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
TYPE_NAME = {"criterion": "criterion", "criterion_list": "criterion list", "categorical": "categorical",
             "record": "record"}


def main() -> None:
    fw = framework_mod.load()
    codes = fw["source_codes"]
    n = sum(len(s["indicators"]) for s in fw["subdimensions"])
    L = ["# Evaluation framework", "",
         f"Dimension: {fw['dimension']}. The framework has {len(fw['subdimensions'])} subdimensions and {n} "
         "indicators. This document is generated by `scripts/llm/framework_doc.py` from `framework/framework.json`, "
         "which `scripts/llm/parse_framework.py` builds from `framework/gender_survey_framework.html`; the "
         "indicator texts are the ones sent to the model.", "",
         "Source types: " + "; ".join(f"{k}, {v}" for k, v in codes.items()) + ".", "",
         "Each indicator is classified by the kind of answer it requires. A criterion is a statement about the "
         "instrument that can only be true or false. A criterion list groups several such statements under one "
         "indicator and evaluates each of them separately. A categorical indicator asks which option, from a fixed "
         "set, describes what the instrument does. A record indicator asks for the relevant text to be copied "
         "exactly as it appears in the documentation. Only criteria and criterion lists produce labels (met, "
         "partially met or unmet) that can be compared across countries.", ""]
    for s in fw["subdimensions"]:
        L += [f"## {s['tag']}. {s['title']}", "", f"Variable: {s['variable']}", ""]
        for ind in s["indicators"]:
            src = ", ".join(f"{c} ({codes[c]})" for c in ind["source_code"].split("+"))
            L += [f"### {ind['indicator_id']}", "",
                  f"Type: {TYPE_NAME[ind['type']]}. Sources: {src}.", ""]
            if ind["type"] == "criterion_list":
                L += [f"Question: {ind['text']}", "", "Elements:", ""]
                statements = ind.get("statements") or [None] * len(ind["elements"])
                L += [f"- `{e}`" + (f": {st}" if st else "") for e, st in zip(ind["elements"], statements)]
                L.append("")
            else:
                L += [ind["text"], ""]
                if ind["type"] == "categorical":
                    L += ["Options:", ""] + [f"- {o}" for o in ind["options"]] + [""]
    text = "\n".join(L)
    assert "—" not in text, "an em dash found its way into FRAMEWORK.md"
    out = framework_mod.PATH.parent / "FRAMEWORK.md"
    out.write_text(text, encoding="utf-8")
    print(f"-> {out.relative_to(ROOT)} ({len(fw['subdimensions'])} subdimensions, {n} indicators)")


if __name__ == "__main__":
    main()
